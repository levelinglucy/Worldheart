"""Stopped-world copy-out integration probe using genuine locally generated v0.2 CLI data.

These tests never load external pickle or touch a user's saves. They exercise the
research-only full-folder copier against a checkpoint generated by the historical
script as __main__, and resume the isolated result using the current CLI. Both
working worlds live in disposable directories. No automatic migration is enabled.
"""

import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest

from experiments.offline_world_copy_spike import (
    SAVE_DIR, SAVE_FILE, prepare_offline_copy,
)

ROOT = Path(__file__).resolve().parents[1]
LEGACY = ROOT / "Worldheart simulator"
CANDIDATE = ROOT / "worldheart_v02_1.py"
EVENTS = "worldheart_v02_events.jsonl"


@unittest.skipUnless(
    hasattr(os, "link") and hasattr(os, "O_NOFOLLOW") and hasattr(os, "O_NONBLOCK"),
    "stopped-world copy-out requires hard-link and guarded-open support",
)
class OfflineWorldCliRecoveryTests(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory(prefix="worldheart-real-copy-out-")
        self.addCleanup(tmp.cleanup)
        self.root = Path(tmp.name)
        self.source_root = self.root / "original"
        self.source_root.mkdir()
        self.destination = self.root / "candidate-roots"
        self.destination.mkdir()
        self.source_data = self.source_root / SAVE_DIR

    def run_cli(self, script, cwd, commands, success=True):
        process = subprocess.run(
            [sys.executable, str(script)], input=commands, text=True,
            encoding="utf-8", errors="replace", stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT, cwd=str(cwd), timeout=90, check=False,
        )
        if success:
            self.assertEqual(process.returncode, 0, process.stdout[-2500:])
        else:
            self.assertNotEqual(process.returncode, 0, process.stdout[-2500:])
        return process.stdout

    def make_legacy_hardlinked_fixture(self):
        self.run_cli(LEGACY, self.source_root, "777\ns\nq\n")
        latest = self.source_data / SAVE_FILE
        envelope = json.loads(latest.read_text(encoding="utf-8"))
        self.assertEqual((envelope["version"], envelope["seed"], envelope["tick"]),
                         ("0.2-primordial", 777, 0))
        snapshot = self.source_data / "snapshot_t000000000000.wh"
        try:
            os.link(latest, snapshot)
        except (OSError, NotImplementedError) as exc:
            self.skipTest("cannot create fixture hard link: %s" % exc)
        # This fossil-shaped byte sentinel tests tree preservation, not fossil
        # generation or recovery by the simulator.
        (self.source_data / "fossil_000000000000.json").write_bytes(b'{"tick":0}\n')
        self.assertEqual(latest.stat().st_ino, snapshot.stat().st_ino)
        return snapshot.name

    @staticmethod
    def content_map(data):
        return {entry.name: entry.read_bytes() for entry in data.iterdir()}

    def test_real_legacy_copy_recovers_and_saves_independently(self):
        snapshot_name = self.make_legacy_hardlinked_fixture()
        original = self.content_map(self.source_data)
        root, manifest = prepare_offline_copy(self.source_data, self.destination)
        copied = root / SAVE_DIR
        control_root = self.root / "direct-control"
        control_root.mkdir()
        shutil.copytree(self.source_data, control_root / SAVE_DIR)
        control_data = control_root / SAVE_DIR

        self.assertTrue(manifest["copy_complete"])
        self.assertFalse(manifest["recovery_review_required"])
        self.assertEqual(self.content_map(copied), original)
        self.assertEqual(self.content_map(control_data), original)
        self.assertEqual((copied / SAVE_FILE).stat().st_nlink, 1)
        self.assertEqual((copied / snapshot_name).stat().st_nlink, 1)
        self.assertNotEqual((copied / SAVE_FILE).stat().st_ino,
                            (copied / snapshot_name).stat().st_ino)
        self.assertEqual(self.content_map(self.source_data), original)

        # The copy and a separately independently copied direct-file control
        # should both recover the same genuine historical __main__.World state.
        for commands, expected_tick in (("y\nq\n", 0), ("y\nrun 1\nq\n", 120)):
            before_events = copied.joinpath(EVENTS).read_text(encoding="utf-8").splitlines()
            for cwd in (root, control_root):
                output = self.run_cli(CANDIDATE, cwd, commands)
                self.assertIn("Recovered transition", output)
            copy_files = self.content_map(copied)
            direct_files = self.content_map(control_data)
            # Pickle serialization does not promise canonical bytes. Compare
            # semantic envelope fields and the actual append-only journal.
            for files in (copy_files, direct_files):
                saved = json.loads(files[SAVE_FILE].decode("utf-8"))
                self.assertEqual((saved["version"], saved["seed"], saved["tick"]),
                                 ("0.2.1-rc1", 777, expected_tick))
                self.assertEqual(files[snapshot_name], original[snapshot_name])
                self.assertEqual(files["fossil_000000000000.json"],
                                 original["fossil_000000000000.json"])
                event_lines = files[EVENTS].decode("utf-8").splitlines()
                self.assertEqual(event_lines[:len(before_events)], before_events)
                self.assertEqual(json.loads(event_lines[-1])["kind"], "CHECKPOINT")
            self.assertEqual(copy_files[EVENTS], direct_files[EVENTS])
            self.assertEqual(self.content_map(self.source_data), original)
        self.assertEqual((self.source_data / SAVE_FILE).stat().st_ino,
                         (self.source_data / snapshot_name).stat().st_ino)

    def test_real_legacy_copy_with_unresolved_temp_refuses_resave(self):
        self.make_legacy_hardlinked_fixture()
        temp_name = SAVE_FILE + ".tmp"
        evidence = b"unfinished checkpoint evidence; preserve for inspection"
        (self.source_data / temp_name).write_bytes(evidence)
        original = self.content_map(self.source_data)
        root, manifest = prepare_offline_copy(self.source_data, self.destination)
        copied = root / SAVE_DIR
        self.assertTrue(manifest["recovery_review_required"])
        self.assertEqual(manifest["unresolved_temp_names"], [temp_name])
        output = self.run_cli(CANDIDATE, root, "y\nq\n", success=False)
        self.assertIn("Unresolved checkpoint temp", output)
        self.assertEqual(self.content_map(copied), original)
        self.assertEqual(self.content_map(self.source_data), original)


if __name__ == "__main__":
    unittest.main()
